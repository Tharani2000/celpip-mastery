"use client";
import { useState } from "react";
import { Sparkles, Check } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Skeleton } from "@/components/ui/skeleton";
import { Notice } from "@/components/ui/notice";
import { api } from "@/lib/client";
type Plan = { focus: string; plan: { skill: string; activity: string; minutes: number; why: string }[] };
export function AiPlanButton() {
  const [state, setState] = useState<"idle" | "loading" | "done">("idle"); const [plan, setPlan] = useState<Plan | null>(null); const [notice, setNotice] = useState<string | null>(null);
  const run = async () => { setState("loading"); try { const r = await api<{ plan: Plan | null; notice: string | null }>("/api/recommendations", { method: "POST" }); setPlan(r.plan); setNotice(r.notice); } catch (e) { setNotice((e as Error).message); } setState("done"); };
  if (state === "loading") return <Skeleton className="h-24" />;
  return <div className="space-y-3">
    {plan && <div className="space-y-2 rounded-xl border bg-secondary/50 p-4"><b>{plan.focus}</b><ul className="space-y-2">{plan.plan.map((p) => <li key={p.activity} className="flex gap-2"><Check className="mt-0.5 size-4 shrink-0 text-success" /><span><b>{p.activity}</b> <span className="text-muted-foreground">({p.minutes} min)</span><br /><span className="text-sm text-muted-foreground">{p.why}</span></span></li>)}</ul><p className="text-xs text-muted-foreground">Generated by AI from your practice data.</p></div>}
    {notice && <Notice tone="warning">{notice}</Notice>}
    {state === "idle" && <Button variant="outline" onClick={run}><Sparkles />Build a plan with AI</Button>}
  </div>;
}
